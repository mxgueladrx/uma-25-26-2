-- 8
DROP MATERIALIZED VIEW VM_PRODUCTO;
CREATE MATERIALIZED VIEW VM_PRODUCTO
REFRESH NEXT SYSDATE + 1/24
AS SELECT CODIGO_BARRAS, DESCRIPCION, STOCK, NOMBRE_CATEGORIA, PRECIO_ACTUAL + (PRECIO_ACTUAL * IVA/100) AS PVP 
FROM PRODUCTO 
JOIN CATEGORIA ON PRODUCTO.CATEGORIA = CATEGORIA.ID;