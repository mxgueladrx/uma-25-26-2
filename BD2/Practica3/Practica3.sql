-- Ejercicio 3
CREATE TABLE MENSAJES_TEXTO AS SELECT CODIGO, TEXTO FROM MENSAJES;
CREATE TABLE MENSAJES_TIPO AS SELECT CODIGO, TIPO FROM MENSAJES;
DROP TABLE MENSAJES;

CREATE VIEW VW_MENSAJES AS
SELECT TX.CODIGO, TX.TEXTO, TI.TIPO FROM MENSAJES_TEXTO TX JOIN MENSAJES_TIPO TI ON TX.CODIGO = TI.CODIGO;

SELECT * FROM VW_MENSAJES; 

/* Si sale lo mismo que antes. No deja hacer inserciones porque la vista depende de dos tablas y si añadimos algún dato no 
sabe a que tabla almacenar el dato. Se puede arreglar con un trigger que al insertar un valor a la vista se almacene en 
ambas tablas */

CREATE TRIGGER TR_MENSAJES
INSTEAD OF INSERT ON VW_MENSAJES
FOR EACH ROW
BEGIN
    INSERT INTO MENSAJES_TEXTO VALUES (:NEW.CODIGO, :NEW.TEXTO);
    INSERT INTO MENSAJES_TIPO VALUES (:NEW.CODIGO, :NEW.TIPO);
END;
