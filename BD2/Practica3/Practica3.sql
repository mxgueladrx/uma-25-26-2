CREATE TRIGGER tr_mensajes_info
AFTER INSERT OR DELETE OR UPDATE ON MENSAJES
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        UPDATE MENSAJES_Info SET CUANTOS_MENSAJES = CUANTOS_MENSAJES + 1, ULTIMO = :NEW.TEXTO WHERE TIPO = :NEW.TIPO;
    ELSIF DELETING THEN
        UPDATE MENSAJES_Info SET CUANTOS_MENSAJES = CUANTOS_MENSAJES - 1, ULTIMO = NULL WHERE TIPO = :OLD.Tipo;
    ELSE
        IF :OLD.TIPO <> :NEW.TIPO THEN
            UPDATE MENSAJES_Info SET CUANTOS_MENSAJES = CUANTOS_MENSAJES - 1, ULTIMO = NULL WHERE TIPO = :OLD.TIPO;
            UPDATE MENSAJES_Info SET CUANTOS_MENSAJES = CUANTOS_MENSAJES + 1, ULTIMO = :NEW.TEXTO WHERE TIPO = :NEW.TIPO;
        ELSE
            UPDATE MENSAJES_Info 
            SET ULTIMO = :NEW.TEXTO 
            WHERE TIPO = :NEW.TIPO;
        END IF;
    END IF;
END;
