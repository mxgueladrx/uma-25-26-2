    Codigo NUMBER(20) PRIMARY KEY,
    Texto VARCHAR2(200)
);

CREATE TABLE AUDITA_MENSAJES (
    Quien VARCHAR2(20),
    Como VARCHAR2(20),
    Cuando DATE
);

CREATE OR REPLACE TRIGGER tr_audita_mensajes
AFTER INSERT OR DELETE OR UPDATE ON MENSAJES
BEGIN
    IF INSERTING THEN
        INSERT INTO AUDITA_MENSAJES VALUES (USER, 'INSERT', SYSDATE);
    ELSIF DELETING THEN
        INSERT INTO AUDITA_MENSAJES VALUES (USER, 'DELETE', SYSDATE);
    ELSE
        INSERT INTO AUDITA_MENSAJES VALUES (USER, 'UPDATE', SYSDATE);
    END IF;
END;
