ALTER TABLE TB_OBJETOS ADD (
    ESTADO VARCHAR2(128),
    NOMBRE_CORRECTO VARCHAR2(128)
);

CREATE OR REPLACE PROCEDURE PR_COMPROBAR(ESQUEMA IN VARCHAR2 DEFAULT NULL) IS
    CURSOR C_OBJECTS IS
        SELECT NOMBRE, TIPO, ESQUEMA_ORIGINAL
        FROM TB_OBJETOS
        WHERE UPPER(ESQUEMA_ORIGINAL) = NVL(UPPER(ESQUEMA), UPPER(ESQUEMA_ORIGINAL))
        FOR UPDATE;

    V_ESTADO VARCHAR2(128);
    V_NOMBRE VARCHAR2(128);
    V_PREFIJO VARCHAR2(128);
BEGIN
    FOR OBJ IN C_OBJECTS LOOP
        V_PREFIJO := NULL;

        BEGIN
            SELECT PREFIJO INTO V_PREFIJO
            FROM TB_ESTILO
            WHERE UPPER(TIPO_OBJETO) = UPPER(OBJ.TIPO);
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                V_PREFIJO := NULL;
        END;

        IF V_PREFIJO IS NULL THEN
            V_ESTADO := 'SIN REGLA';
            V_NOMBRE := OBJ.NOMBRE;
        ELSIF UPPER(OBJ.NOMBRE) LIKE UPPER(V_PREFIJO) || '%' THEN
            V_ESTADO := 'CORRECTO';
            V_NOMBRE := OBJ.NOMBRE;
        ELSE
            V_ESTADO := 'INCORRECTO';
            V_NOMBRE := SUBSTR(V_PREFIJO || OBJ.NOMBRE, 1, 128);
        END IF;

        UPDATE TB_OBJETOS
        SET ESTADO = V_ESTADO, 
            NOMBRE_CORRECTO = V_NOMBRE
        WHERE CURRENT OF C_OBJECTS;
    END LOOP;
    COMMIT;
END;
/

EXECUTE PR_COMPROBAR();

