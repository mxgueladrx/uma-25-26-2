DROP TABLE TB_OBJETOS;

CREATE TABLE TB_OBJETOS (
    NOMBRE VARCHAR2(128),
    CODIGO NUMBER PRIMARY KEY,
    FECHA_CREACION DATE,
    FECHA_MODIFICACION DATE,
    TIPO VARCHAR2(128),
    ESQUEMA_ORIGINAL VARCHAR2(128)
);

SELECT * FROM ALL_OBJECTS;

DECLARE 
    CURSOR C_OBJECTS IS
        SELECT OBJECT_NAME, OBJECT_ID, CREATED, LAST_DDL_TIME, OBJECT_TYPE, OWNER
        FROM ALL_OBJECTS;
BEGIN
    FOR OBJ IN C_OBJECTS LOOP
        INSERT INTO TB_OBJETOS (NOMBRE, CODIGO, FECHA_CREACION, FECHA_MODIFICACION, TIPO, ESQUEMA_ORIGINAL)
        VALUES(OBJ.OBJECT_NAME, OBJ.OBJECT_ID, OBJ.CREATED, OBJ.LAST_DDL_TIME, OBJ.OBJECT_TYPE, OBJ.OWNER);
    END LOOP;
    COMMIT;
END;
